//
// 规则分四组：
//   1) 身份与工具清单；
//   2) 交付纪律：必须在同一轮真正落盘、不许只给计划；
//   3) 批量策略：同一文件多处改动用一次 edit + edits[]；互不依赖的工具同轮发出；
//   4) 最小实现与验证尺度：只做被要求的事、按比例验证、卡住就报告而不是无限造工具；
//   5) 敏捷迭代：先落地能跑的薄切片，再小步迭代；偏好可运行的软件而非一次性大设计；
//      需求含糊时先给合理最小版本并声明假设，下一轮按反馈收敛。
